using System.Text;

namespace ChestCounter;

internal static class AppSecrets
{
    private static readonly byte[] M1 = [0x6D, 0xA3, 0x19, 0xE4, 0x52, 0x8F, 0xC7, 0x3B];
    private static readonly byte[] M2 = [0x94, 0x2E, 0xD1, 0x47, 0xB8, 0x0C, 0x73, 0xF5];

    private static readonly byte[] D = [0x34, 0xC9, 0xB4, 0xCD, 0x79, 0x22, 0xDF, 0x63, 0xC4, 0xE1, 0x0D, 0xBD, 0x09, 0xD2, 0xA7, 0x7B, 0xF4, 0x56, 0x1D];
    private static readonly byte[] F = [0x91, 0xD6, 0xB5, 0x69, 0x1E, 0x59, 0x4D, 0xF2, 0x86, 0x14, 0xF0, 0xE1, 0x55, 0xE9, 0x15, 0xAA, 0x8C, 0xBC, 0xEA, 0xE1, 0x35, 0x89, 0xD5, 0x10, 0xE6, 0x3E, 0xDA, 0x76, 0x67, 0x23, 0x8D, 0x2A, 0x34, 0x55, 0xAA, 0x8C];

    private static string? _discordAppId;
    private static string? _fortniteApiKey;

    public static string DiscordAppId => _discordAppId ??= Unpack(D, M1, 0x4A);
    public static string FortniteApiKey => _fortniteApiKey ??= Unpack(F, M2, 0x71);

    private static string Unpack(byte[] data, byte[] mask, byte salt)
    {
        var buf = new byte[data.Length];
        for (var i = 0; i < data.Length; i++)
        {
            var r = data[i];
            var b = (byte)(((r >> 3) | (r << 5)) & 0xFF);
            var k = (byte)((mask[i % mask.Length] + (i * 31) + salt) & 0xFF);
            buf[i] = (byte)(b ^ k);
        }
        return Encoding.UTF8.GetString(buf);
    }
}
